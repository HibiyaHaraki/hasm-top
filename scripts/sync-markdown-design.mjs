// ###################################################
// File Name : sync-markdown-design.mjs
// Purpose : Keep the hasm-top landing page design in sync with the real
//           HASM Markdown Editor look & feel, without editing the
//           hasm_markdown submodule.
// Description : Reads submodules/hasm_markdown/src/main.css and
//               HASM_Markdown_Editor.jsx, extracts the design tokens
//               (colors, markdown-syntax classes) and the exact
//               highlightMarkdown() logic, and regenerates
//               src/generated/markdown-design-tokens.css and
//               src/generated/markdownHighlight.js. Run automatically
//               before dev/build via package.json, so any change made
//               upstream in hasm_markdown is picked up on the next
//               `npm run dev` / `npm run build`.
// ###################################################

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createLogger } from "../src/hasm_logger/src/react/logger.js";

const logger = createLogger("sync-markdown-design");

const REPO_ROOT = path.resolve(fileURLToPath(import.meta.url), "..", "..");

const SOURCE_CSS = path.join(REPO_ROOT, "submodules", "hasm_markdown", "src", "main.css");
const SOURCE_EDITOR = path.join(REPO_ROOT, "submodules", "hasm_markdown", "src", "HASM_Markdown_Editor.jsx");

const OUTPUT_DIR = path.join(REPO_ROOT, "src", "generated");
const OUTPUT_CSS = path.join(OUTPUT_DIR, "markdown-design-tokens.css");
const OUTPUT_JS = path.join(OUTPUT_DIR, "markdownHighlight.js");

// CSS selectors/rules whose colors & typography define the editor's visual identity.
const TARGET_TOKENS = [
  ":root",
  ".MarkdownSyntax_EditorSurface",
  ".MarkdownSyntax_Input",
  ".MarkdownSyntax_Heading",
  ".MarkdownSyntax_Marker",
  ".MarkdownSyntax_Quote",
  ".MarkdownSyntax_Link",
  ".MarkdownSyntax_Code",
  ".MarkdownSyntax_Strong",
  ".MarkdownSyntax_Emphasis",
  ".EditorColor_light",
  ".EditorColor_dark",
  ".HASM_Markdown_Editor_EditorCol_Title",
  ".HASM_Markdown_Editor_ViewerCol_Title",
  ".HASM_Markdown_Editor_ViewerCol_Viewer",
  ".HASM_Markdown_Editor_EditorCol_Editor_LineNum",
];

function extractTopLevelBlocks(css) {
  const blocks = [];
  let depth = 0;
  let selectorStart = 0;
  const stack = [];
  for (let i = 0; i < css.length; i += 1) {
    const ch = css[i];
    if (ch === "{") {
      if (depth === 0) stack.push({ selectorStart, braceStart: i });
      depth += 1;
    } else if (ch === "}") {
      depth -= 1;
      if (depth === 0) {
        const cur = stack.pop();
        blocks.push({
          selector: css.slice(cur.selectorStart, cur.braceStart).trim(),
          full: css.slice(cur.selectorStart, i + 1),
        });
        selectorStart = i + 1;
      }
    }
  }
  return blocks;
}

function extractDesignCss() {
  // Preserve only the upstream selectors that define the editor's shared visual language.
  const css = readFileSync(SOURCE_CSS, "utf8");
  const blocks = extractTopLevelBlocks(css);
  const matched = blocks.filter(
    (block) => !block.selector.startsWith("@") && TARGET_TOKENS.some((token) => block.selector.includes(token)),
  );
  return matched.map((block) => block.full).join("\n\n");
}

function extractHighlightFunction() {
  // Copy the implementation rather than reimplementing syntax highlighting in the landing page.
  const source = readFileSync(SOURCE_EDITOR, "utf8");
  const startMatch = source.match(/function highlightMarkdown\([^)]*\)\s*{/);
  if (!startMatch) {
    throw new Error("highlightMarkdown() not found in HASM_Markdown_Editor.jsx");
  }
  const bodyStart = startMatch.index + startMatch[0].length;
  let depth = 1;
  let i = bodyStart;
  while (depth > 0 && i < source.length) {
    if (source[i] === "{") depth += 1;
    else if (source[i] === "}") depth -= 1;
    i += 1;
  }
  return source.slice(startMatch.index, i);
}

if (!existsSync(SOURCE_CSS) || !existsSync(SOURCE_EDITOR)) {
  // Submodule not checked out; keep whatever was previously generated instead of blocking dev/build.
  logger.warn("hasm_markdown source files not found; skipping design sync.", { sourceCss: SOURCE_CSS, sourceEditor: SOURCE_EDITOR });
  process.exit(0);
}

// Generated output is kept in one directory so Vite can import the synced design contract.
mkdirSync(OUTPUT_DIR, { recursive: true });

const header = (relSource) =>
  `/* AUTO-GENERATED by scripts/sync-markdown-design.mjs from ${relSource}. Do not edit by hand — re-run "npm run sync:markdown-design" instead. */\n\n`;

writeFileSync(
  OUTPUT_CSS,
  header("submodules/hasm_markdown/src/main.css") + extractDesignCss() + "\n",
);

const highlightFn = extractHighlightFunction();
writeFileSync(
  OUTPUT_JS,
  header("submodules/hasm_markdown/src/HASM_Markdown_Editor.jsx") +
    `export ${highlightFn}\n`,
);

logger.info("Synced markdown design tokens and highlightMarkdown() from hasm_markdown.", {
  outputCss: OUTPUT_CSS,
  outputJs: OUTPUT_JS,
});
